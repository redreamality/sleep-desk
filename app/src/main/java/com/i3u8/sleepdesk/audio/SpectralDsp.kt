/** Double-precision DSP for the frozen 16 kHz Python feature pipeline. */
internal object SpectralDsp {
    // Covers the study's 15 s clips, bounds Bluestein scratch to four 524288 arrays.
    private const val MAX_SAMPLES = 262144

    /**
     * In-place complex DFT, negative forward sign and inverse normalization by N.
     * Accepts 1..262144 samples, including prime lengths; arrays must not alias.
     * Interruption throws CancellationException without clearing the interrupt flag.
     * An interrupted transform may leave its input partially transformed.
     */
    fun fft(real: DoubleArray, imag: DoubleArray, inverse: Boolean = false) {
        require(real.size == imag.size && real.size in 1..MAX_SAMPLES)
        require(real !== imag) { "FFT arrays must not alias" }
        checkCancelled()
        for (i in real.indices) {
            checkpoint(i)
            require(real[i].isFinite() && imag[i].isFinite()) { "Nonfinite FFT input" }
        }
        // Swapping real/imag implements conjugation on both sides of the forward DFT.
        if (inverse) {
            forward(imag, real)
            for (i in real.indices) {
                checkpoint(i)
                real[i] /= real.size.toDouble()
                imag[i] /= real.size.toDouble()
            }
        } else {
            forward(real, imag)
        }
    }

    private fun forward(real: DoubleArray, imag: DoubleArray) {
        if (real.size and (real.size - 1) == 0) radix2(real, imag) else bluestein(real, imag)
    }

    private fun radix2(real: DoubleArray, imag: DoubleArray) {
        val n = real.size
        var j = 0
        for (i in 1 until n) {
            checkpoint(i)
            var bit = n shr 1
            while (j and bit != 0) {
                j = j xor bit
                bit = bit shr 1
            }
            j = j xor bit
            if (i < j) {
                val r = real[i]
                real[i] = real[j]
                real[j] = r
                val v = imag[i]
                imag[i] = imag[j]
                imag[j] = v
            }
        }
        var width = 2
        while (width <= n) {
            checkCancelled()
            val half = width / 2
            // Direct twiddles avoid the accumulated drift of a long recurrence.
            for (k in 0 until half) {
                checkpoint(k)
                val angle = -2.0 * PI * k / width
                val c = cos(angle)
                val s = sin(angle)
                var a = k
                while (a < n) {
                    checkpoint(a - k)
                    val b = a + half
                    val r = real[b] * c - imag[b] * s
                    val v = real[b] * s + imag[b] * c
                    real[b] = real[a] - r
                    imag[b] = imag[a] - v
                    real[a] += r
                    imag[a] += v
                    a += width
                }
            }
            width = width shl 1
        }
    }

    private fun bluestein(real: DoubleArray, imag: DoubleArray) {
        val n = real.size
        var length = 1
        while (length < 2 * n - 1) length = length shl 1
        checkCancelled()
        val ar = DoubleArray(length)
        val ai = DoubleArray(length)
        val br = DoubleArray(length)
        val bi = DoubleArray(length)
        for (i in 0 until n) {
            checkpoint(i)
            // Long arithmetic and modular reduction prevent overflow/large-angle error.
            val angle = PI * ((i.toLong() * i) % (2L * n)).toDouble() / n
            val c = cos(angle)
            val s = sin(angle)
            ar[i] = real[i] * c + imag[i] * s
            ai[i] = imag[i] * c - real[i] * s
            br[i] = c
            bi[i] = s
            if (i != 0) {
                br[length - i] = c
                bi[length - i] = s
            }
        }
        radix2(ar, ai)
        radix2(br, bi)
        for (i in 0 until length) {
            checkpoint(i)
            val r = ar[i] * br[i] - ai[i] * bi[i]
            ai[i] = ar[i] * bi[i] + ai[i] * br[i]
            ar[i] = r
        }
        radix2(ai, ar)
        for (i in 0 until n) {
            checkpoint(i)
            val angle = PI * ((i.toLong() * i) % (2L * n)).toDouble() / n
            val c = cos(angle)
            val s = sin(angle)
            real[i] = (ar[i] * c + ai[i] * s) / length
            imag[i] = (ai[i] * c - ar[i] * s) / length
        }
    }

    /**
     * The five env.mod_* values only. Input is already-preprocessed finite mono
     * 16 kHz PCM, nonempty and at most 262144 samples; it is never modified.
     * No additional mean removal or peak normalization is applied to the PCM.
     * Coroutine callers must arrange thread interruption (e.g. runInterruptible).
     */
    fun modulation(y: DoubleArray): Map<String, Double> {
        require(y.size in 1..MAX_SAMPLES) { "Expected 1..262144 PCM samples" }
        checkCancelled()
        val real = y.copyOf()
        val imag = DoubleArray(y.size)
        for (i in y.indices) {
            checkpoint(i)
            require(y[i].isFinite()) { "Nonfinite PCM" }
        }
        for (sos in SOS) {
            var z1 = 0.0
            var z2 = 0.0
            for (i in real.indices) {
                checkpoint(i)
                val x = real[i]
                val value = sos[0] * x + z1
                z1 = sos[1] * x - sos[4] * value + z2
                z2 = sos[2] * x - sos[5] * value
                real[i] = value
            }
        }
        fft(real, imag)
        for (i in real.indices) {
            checkpoint(i)
            val factor = when {
                i == 0 || (real.size % 2 == 0 && i == real.size / 2) -> 1.0
                i <= (real.size - 1) / 2 -> 2.0
                else -> 0.0
            }
            real[i] *= factor
            imag[i] *= factor
        }
        fft(real, imag, inverse = true)
        for (i in real.indices) {
            checkpoint(i)
            real[i] = hypot(real[i], imag[i])
        }
        val m = (y.size + 79) / 80
        val envelope = DoubleArray(m)
        // SciPy pre-pads FIR by 80 and removes 11 outputs:
        // (j + 11)*80 - 80 == j*80 + 800 in the unpadded convolution.
        for (j in 0 until m) {
            checkCancelled()
            val center = j * 80
            var value = 0.0
            for (i in max(0, center - 800)..min(real.lastIndex, center + 800)) {
                value += real[i] * RESAMPLE_FIR[center + 800 - i]
            }
            envelope[j] = value
        }
        val mean = envelope.sum() / m
        for (i in envelope.indices) {
            checkpoint(i)
            val window = if (m == 1) 1.0 else 0.5 - 0.5 * cos(2.0 * PI * i / (m - 1))
            envelope[i] = (envelope[i] - mean) * window
        }
        val spectrumImag = DoubleArray(m)
        fft(envelope, spectrumImag)
        val bands = DoubleArray(5)
        var total = 0.0
        for (i in 0..m / 2) {
            checkpoint(i)
            // Match np.fft.rfftfreq's reciprocal-then-multiply ordering.
            val hz = i * (1.0 / (m * (1.0 / 200.0)))
            if (hz < 0.5 || hz >= 90.0) continue
            val power = envelope[i] * envelope[i] + spectrumImag[i] * spectrumImag[i]
            val band = when {
                hz < 3.0 -> 0
                hz < 8.0 -> 1
                hz < 20.0 -> 2
                hz < 50.0 -> 3
                else -> 4
            }
            bands[band] += power
            total += power
        }
        require(total.isFinite()) { "PCM magnitude overflowed modulation power" }
        val denominator = max(total, 1e-18)
        return KEYS.indices.associate { KEYS[it] to bands[it] / denominator }
    }

    private fun checkpoint(index: Int) {
        if (index and 1023 == 0) checkCancelled()
    }

